// One-time (quarterly-at-most) import script — see lib/design/data/PROVENANCE.md and build
// plan §3.1/§3.4. Reads a CSV from a pinned-SHA checkout of nextlevelbuilder's
// ui-ux-pro-max-skill repo (MIT) and writes the matching lib/design/data/*.json file.
//
// Never run as part of the app or the build — this is a standalone developer script, invoked
// by hand. The app reads only the committed JSON; nothing at runtime parses a CSV. Re-running
// this script overwrites the target JSON and that file's own section of PROVENANCE.md from
// scratch every time — it is not incremental and does not merge with a prior run of the SAME
// file. Re-importing colors does not touch typography's PROVENANCE.md section or vice versa
// (see writeProvenanceSection below) — each generated file owns exactly one section.
//
// GENERATED FILE WARNING: lib/design/data/palettes.json and lib/design/data/typography.json
// are both generated by this script. Never hand-edit either directly — a future re-import
// silently discards any hand edit, since this script always writes its target from scratch.
// Corrections belong in a sibling lib/design/data/overrides.json (not created by this import —
// wire it in at the point something actually needs correcting), merged at build time by
// whatever eventually reads the generated JSON. This warning is repeated at the top of
// PROVENANCE.md, since JSON has no comment syntax to carry it inside the generated files
// themselves without breaking `jq 'length'` on what must stay a plain array — see Task 1.4's
// log entry in docs/kondo-v2-execution.md for why that tension exists and how it's resolved.
//
// Usage:
//   npx tsx lib/design/build/import-uupm.ts --file colors --source <path> --sha <upstream-commit-sha>
//   npx tsx lib/design/build/import-uupm.ts --file typography --source <path> --sha <upstream-commit-sha>
//
// --file selects which upstream CSV to import — required, no default, so a bare invocation
// can't silently import the wrong file.
// --source accepts either a path directly to the target CSV, or the root of a uupm clone (in
// which case src/ui-ux-pro-max/data/<file>.csv is read from inside it).
// --sha is required and not auto-detected from the source clone's git state — pinning is a
// deliberate, stated act per import, not something this script infers on your behalf.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";

const REPO_URL = "https://github.com/nextlevelbuilder/ui-ux-pro-max-skill";
const OUT_DIR = path.resolve(__dirname, "../data");
const PROVENANCE_PATH = path.join(OUT_DIR, "PROVENANCE.md");

const PROVENANCE_PREAMBLE = `# Provenance — lib/design/data/*.json

**GENERATED FILES. Do not hand-edit \`palettes.json\` or \`typography.json\`.** Each is fully
overwritten every time \`lib/design/build/import-uupm.ts\` runs for that file — a hand edit
survives only until the next re-import of the same file, which silently discards it.
Corrections belong in a sibling \`lib/design/data/overrides.json\` (not created by either
import — wire it in at the point something actually needs correcting), merged at build time by
whatever reads the generated JSON. This is the same warning \`import-uupm.ts\`'s own header
comment carries — repeated here because JSON has no comment syntax, so it can't live inside the
generated files themselves without breaking \`jq 'length'\` on what must stay a plain array.

This file has one section per generated JSON file, each independently regenerated by its own
import run — importing \`typography\` does not touch the \`palettes.json\` section below and
vice versa.
`;

// ---------------------------------------------------------------------------------------------
// Shared: arg parsing, CSV parsing, line-ending normalisation, PROVENANCE.md section merge
// ---------------------------------------------------------------------------------------------

type FileKey = "colors" | "typography";

function parseArgs(argv: string[]): { file: FileKey; source: string; sha: string } {
  const args = new Map<string, string>();
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith("--")) {
      args.set(argv[i].slice(2), argv[i + 1]);
      i++;
    }
  }
  const file = args.get("file");
  const source = args.get("source");
  const sha = args.get("sha");
  if (file !== "colors" && file !== "typography") {
    throw new Error(
      `Usage: npx tsx lib/design/build/import-uupm.ts --file colors|typography --source <path> --sha <upstream-commit-sha>`
    );
  }
  if (!source || !sha) {
    throw new Error(
      `Usage: npx tsx lib/design/build/import-uupm.ts --file ${file} --source <path> --sha <upstream-commit-sha>`
    );
  }
  if (!/^[0-9a-f]{40}$/i.test(sha)) {
    throw new Error(`--sha must be a full 40-character commit SHA, got: ${sha}`);
  }
  return { file, source, sha };
}

function resolveCsvPath(source: string, csvFilename: string): string {
  const asFile = path.resolve(source);
  if (asFile.toLowerCase().endsWith(".csv")) return asFile;
  const insideClone = path.resolve(source, "src/ui-ux-pro-max/data", csvFilename);
  if (existsSync(insideClone)) return insideClone;
  throw new Error(`Could not find ${csvFilename} at ${asFile} or ${insideClone}`);
}

// A small, direct RFC4180 field parser — not a general CSV library, since these files have a
// known, fixed shape to read (colors.csv's 19 quoted Border rows; typography.csv's Google
// Fonts URL / CSS Import / Tailwind Config columns, which contain commas and quotes of their
// own throughout). Assumes LF-only input; call normalizeLineEndings first.
function parseCsv(content: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let inQuotes = false;
  let i = 0;
  while (i < content.length) {
    const char = content[i];
    if (inQuotes) {
      if (char === '"' && content[i + 1] === '"') {
        field += '"';
        i += 2;
        continue;
      }
      if (char === '"') {
        inQuotes = false;
        i++;
        continue;
      }
      field += char;
      i++;
      continue;
    }
    if (char === '"') {
      inQuotes = true;
      i++;
      continue;
    }
    if (char === ",") {
      row.push(field);
      field = "";
      i++;
      continue;
    }
    if (char === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
      i++;
      continue;
    }
    field += char;
    i++;
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

// Normalises CRLF (and any lone CR) to LF before anything else touches the content — parsing
// and the recorded content hash both run on this normalised string, so the digest recorded in
// PROVENANCE.md doesn't depend on which line-ending convention the checkout happened to use
// (the source repo's CSVs are CRLF on disk as vendored; a Windows vs. Unix checkout of the SAME
// commit can still disagree on line endings depending on the cloning machine's git config, even
// though the committed blob is identical).
function normalizeLineEndings(content: string): string {
  return content.replace(/\r\n/g, "\n").replace(/\r/g, "\n");
}

function readAndHashCsv(csvPath: string): { normalized: string; sourceSha256: string } {
  const raw = readFileSync(csvPath, "utf8");
  const normalized = normalizeLineEndings(raw);
  const sourceSha256 = createHash("sha256").update(normalized, "utf8").digest("hex");
  return { normalized, sourceSha256 };
}

// Replaces (or appends, on first run for that file) exactly one file's own
// <!-- BEGIN/END GENERATED SECTION: <key> --> block in the shared PROVENANCE.md, leaving every
// other file's section byte-for-byte untouched. This is what lets `--file colors` and
// `--file typography` be re-run independently without one import clobbering the other's
// recorded provenance.
function writeProvenanceSection(sectionKey: string, sectionBody: string): void {
  const begin = `<!-- BEGIN GENERATED SECTION: ${sectionKey} -->`;
  const end = `<!-- END GENERATED SECTION: ${sectionKey} -->`;
  const block = `${begin}\n${sectionBody}\n${end}`;

  const onDisk = existsSync(PROVENANCE_PATH) ? readFileSync(PROVENANCE_PATH, "utf8") : "";
  // A file with no generated-section markers at all is the pre-2.1, colors-only format (or no
  // file yet) — treated as empty rather than preserved verbatim, so migrating to the sectioned
  // format doesn't leave the old unsectioned prose duplicated above the new section.
  const existing = onDisk.includes("<!-- BEGIN GENERATED SECTION:") ? onDisk : PROVENANCE_PREAMBLE;
  const beginIdx = existing.indexOf(begin);
  let next: string;
  if (beginIdx === -1) {
    // First import of this file — append a new section at the end.
    next = existing.trimEnd() + "\n\n" + block + "\n";
  } else {
    const endIdx = existing.indexOf(end, beginIdx);
    if (endIdx === -1) {
      throw new Error(`Found ${begin} in PROVENANCE.md with no matching ${end} — file is corrupted, refusing to guess.`);
    }
    next = existing.slice(0, beginIdx) + block + existing.slice(endIdx + end.length);
  }
  writeFileSync(PROVENANCE_PATH, next, "utf8");
}


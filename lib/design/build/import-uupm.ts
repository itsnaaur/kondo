const TYPOGRAPHY_EXPECTED_HEADER = [
  "No", "Font Pairing Name", "Category", "Heading Font", "Body Font", "Mood/Style Keywords",
  "Best For", "Google Fonts URL", "CSS Import", "Tailwind Config", "Notes",
];

// Task 2.1. These 13 rows (of 74) are mobile/native-app pairings, not web landing-page ones —
// each is EITHER named "Mobile" in its own Font Pairing Name, OR its Notes field names a
// mobile-only technical constraint with no web equivalent (react-native-linear-gradient,
// react-native-masked-view's MaskedView, windowWidth/PixelRatio-based responsive scaling,
// Expo's useFonts hook, NativeWind, or an OS-level "falls back to system SF/Roboto on
// iOS/Android" strategy). Named explicitly by upstream row number, the same reason
// DROPPED_PRODUCT_TYPE above is a named constant rather than a runtime keyword scan — a future
// re-import should fail loudly if this set no longer matches exactly 13 rows, not silently
// start excluding a different set because upstream's wording shifted. Two rows in this same
// No.58-74 cluster were deliberately NOT included here despite mentioning "mobile" in their own
// Best For column (No. 58 Bauhaus Geometric, No. 59 Minimalist Monochrome Editorial) — both use
// Tailwind CSS utility classes (`text-4xl`, `text-5xl`) in their Notes, a web-CSS-framework
// signal, not a React Native one; "mobile apps" there reads as describing an audience, not an
// implementation constraint. No. 62 (Terminal CLI Monospace) and No. 70 (Web3 Bitcoin DeFi) were
// also considered and kept — see this task's log entry for the full reasoning on all four.
const EXCLUDED_MOBILE_IDS = new Set([
  60, // Modern Dark Cinema (Inter System) — react-native-linear-gradient
  61, // SaaS Mobile Boutique (Calistoga + Inter) — named Mobile
  63, // Kinetic Brutalism (Space Grotesk) — windowWidth/375*size, PixelRatio scaling
  64, // Flat Design Mobile (System Bold) — named Mobile
  65, // Material You MD3 (Roboto System) — Android/MD3, "enterprise mobile", system Roboto on Android
  66, // Neo Brutalism Mobile (Space Grotesk Bold) — named Mobile
  67, // Bold Typography Mobile (Inter Poster) — named Mobile
  68, // Academia Mobile (Cormorant + Crimson + Cinzel) — named Mobile
  69, // Cyberpunk Mobile (Orbitron + JetBrains Mono) — NativeWind / useFonts hook
  71, // Claymorphism Mobile (Nunito + DM Sans) — named Mobile
  72, // Enterprise SaaS Mobile (Plus Jakarta Sans) — iOS Dynamic Type / Android font scaling
  73, // Sketch Hand-Drawn Mobile (Kalam + Patrick Hand) — Expo useFonts
  74, // Neumorphism Mobile (Plus Jakarta Sans + System) — named Mobile
]);
const EXPECTED_EXCLUDED_COUNT = 13;
// Expected count of Heading Font === Body Font rows across the FULL 74-row upstream set —
// independent of, and overlapping with, EXCLUDED_MOBILE_IDS above (7 of the 20 are also mobile-
// excluded; see this task's log entry for the exact overlap). Asserted here for the same
// "the audit reported a number, a mismatch means the import is wrong" reason as
// EXPECTED_EXCLUDED_COUNT.
const EXPECTED_SINGLE_FAMILY_COUNT_ALL = 20;

type TypographyPairing = {
  id: number;
  name: string;
  category: string;
  headingFont: string;
  bodyFont: string;
  singleFamily: boolean;
  moodKeywords: string;
  bestFor: string;
  googleFontsUrl: string;
  cssImport: string;
  tailwindConfig: string;
  notes: string;
};

function rowToPairing(header: string[], row: string[]): TypographyPairing {
  const get = (name: string): string => {
    const idx = header.indexOf(name);
    const value = row[idx];
    if (value === undefined) throw new Error(`Missing column "${name}" in row: ${row.join(",")}`);
    return value;
  };
  const headingFont = get("Heading Font");
  const bodyFont = get("Body Font");
  return {
    id: Number(get("No")),
    name: get("Font Pairing Name"),
    category: get("Category"),
    headingFont,
    bodyFont,
    singleFamily: headingFont === bodyFont,
    moodKeywords: get("Mood/Style Keywords"),
    bestFor: get("Best For"),
    googleFontsUrl: get("Google Fonts URL"),
    cssImport: get("CSS Import"),
    tailwindConfig: get("Tailwind Config"),
    notes: get("Notes"),
  };
}

function importTypography(source: string, sha: string): void {
  const csvPath = resolveCsvPath(source, "typography.csv");
  const { normalized, sourceSha256 } = readAndHashCsv(csvPath);

  const rows = parseCsv(normalized).filter((r) => r.length > 1 || r[0] !== "");
  const [header, ...dataRows] = rows;
  if (header.join(",") !== TYPOGRAPHY_EXPECTED_HEADER.join(",")) {
    throw new Error(
      `typography.csv header changed since this script was written.\nExpected: ${TYPOGRAPHY_EXPECTED_HEADER.join(",")}\nGot:      ${header.join(",")}`
    );
  }

  const totalRowCount = dataRows.length;
  const allPairings = dataRows.map((row) => rowToPairing(header, row));

  const singleFamilyAll = allPairings.filter((p) => p.singleFamily);
  if (singleFamilyAll.length !== EXPECTED_SINGLE_FAMILY_COUNT_ALL) {
    throw new Error(
      `Expected exactly ${EXPECTED_SINGLE_FAMILY_COUNT_ALL} single-family rows (Heading Font === Body Font) across all ${totalRowCount} upstream rows, found ${singleFamilyAll.length}. Aborting rather than importing a shape the plan didn't anticipate.`
    );
  }

  const excludedRows = allPairings.filter((p) => EXCLUDED_MOBILE_IDS.has(p.id));
  if (excludedRows.length !== EXPECTED_EXCLUDED_COUNT) {
    throw new Error(
      `EXCLUDED_MOBILE_IDS names ${EXCLUDED_MOBILE_IDS.size} ids but only ${excludedRows.length} matched real rows — the row numbering has shifted since this script was written. Aborting.`
    );
  }
  const pairings = allPairings.filter((p) => !EXCLUDED_MOBILE_IDS.has(p.id));
  const singleFamilyKept = pairings.filter((p) => p.singleFamily);

  writeFileSync(path.join(OUT_DIR, "typography.json"), JSON.stringify(pairings, null, 2) + "\n", "utf8");

  const importDate = new Date().toISOString().slice(0, 10);
  const excludedList = [...excludedRows].sort((a, b) => a.id - b.id).map((p) => `No. ${p.id} (${p.name})`).join(", ");

  const section = `## typography.json

### Source

- Repository: ${REPO_URL}
- Pinned commit SHA: \`${sha}\`
- Import date: ${importDate}
- File imported: \`src/ui-ux-pro-max/data/typography.csv\`
- Source file SHA-256 (after CRLF→LF normalisation — see palettes.json's section above for why
  normalisation happens before hashing): \`${sourceSha256}\`
- License: MIT — see /THIRD_PARTY_NOTICES.md at the repo root. The 88 distinct Google Fonts
  families referenced by the imported pairings are separately licensed (OFL or Apache-2.0, per
  family) — see /THIRD_PARTY_NOTICES.md's "Google Fonts" section, not this repository's own MIT
  terms.

### Row counts

| File | Upstream rows | Excluded (mobile/native-app) | Imported rows |
|---|---:|---:|---:|
| \`typography.csv\` | ${totalRowCount} | ${excludedRows.length} | ${pairings.length} |

Excluded: ${excludedList}.

### Tagging applied

- \`singleFamily: true\` set on every pairing whose \`Heading Font\` exactly equals its
  \`Body Font\` — kept, not dropped, per this task's instruction. ${singleFamilyAll.length} of the
  full ${totalRowCount} upstream rows are single-family; ${singleFamilyAll.length - singleFamilyKept.length} of those
  are also in the excluded mobile set above, leaving ${singleFamilyKept.length} single-family
  pairings tagged in the ${pairings.length} imported rows.
- No other transformation applied — every other column is imported as-is from the CSV (a plain
  string, including \`Mood/Style Keywords\` and \`Best For\`, deliberately not split into arrays,
  matching \`palettes.json\`'s own "faithful import, minimal transformation" precedent).

### Re-import

Re-import deliberately, quarterly at most — see palettes.json's section above. Gate on
\`validate-fonts.ts\` before re-importing.

    npx tsx lib/design/build/import-uupm.ts --file typography --source <path-to-clone-or-typography.csv> --sha <commit-sha>`;

  writeProvenanceSection("typography.json", section);

  console.log(`Imported ${pairings.length} typography pairings (excluded ${excludedRows.length} mobile/native-app, from ${totalRowCount} upstream rows).`);
  console.log(`Single-family: ${singleFamilyAll.length} of ${totalRowCount} upstream rows; ${singleFamilyKept.length} survive into the imported set, tagged.`);
  console.log(`Source SHA-256 (post-LF-normalisation): ${sourceSha256}`);
  console.log(`Wrote ${path.join(OUT_DIR, "typography.json")}`);
  console.log(`Wrote ${PROVENANCE_PATH} (typography.json section)`);
}

// ---------------------------------------------------------------------------------------------

function main() {
  const { file, source, sha } = parseArgs(process.argv.slice(2));
  if (file === "colors") importColors(source, sha);
  else importTypography(source, sha);
}

main();

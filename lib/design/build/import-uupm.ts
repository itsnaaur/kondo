// One-time (quarterly-at-most) import script — see lib/design/data/PROVENANCE.md and build
// plan §3.1/§3.4. Reads `colors.csv` from a pinned-SHA checkout of nextlevelbuilder's
// ui-ux-pro-max-skill repo (MIT) and writes lib/design/data/palettes.json.
//
// Never run as part of the app or the build — this is a standalone developer script, invoked
// by hand. The app reads only the committed JSON; nothing at runtime parses a CSV. Re-running
// this script overwrites palettes.json and PROVENANCE.md from scratch every time — it is not
// incremental and does not merge with a prior run.
//
// GENERATED FILE WARNING: lib/design/data/palettes.json is generated by this script. Never
// hand-edit it directly — a future re-import silently discards any hand edit, since this
// script always writes from scratch. Corrections belong in a sibling
// lib/design/data/overrides.json, merged at build time by whatever eventually reads
// palettes.json (Task 1.5/1.6 — not built by this script). This warning is repeated at the
// top of PROVENANCE.md, since JSON has no comment syntax to carry it inside palettes.json
// itself without breaking `jq 'length'` on a plain 191-element array — see this task's log
// entry (1.4) in docs/kondo-v2-execution.md for why that tension exists and how it's resolved.
//
// Usage:
//   npx tsx lib/design/build/import-uupm.ts --source <path> --sha <upstream-commit-sha>
//
// --source accepts either a path directly to colors.csv, or the root of a uupm clone (in
// which case src/ui-ux-pro-max/data/colors.csv is read from inside it).
// --sha is required and not auto-detected from the source clone's git state — pinning is a
// deliberate, stated act per import, not something this script infers on your behalf.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";

const REPO_URL = "https://github.com/nextlevelbuilder/ui-ux-pro-max-skill";
const OUT_DIR = path.resolve(__dirname, "../data");

// The row this import deliberately excludes — the single WCAG AA body-text failure the audit
// found (Background #888888 / Foreground #000000). Named explicitly, not filtered by a
// generic contrast check at import time, so a future re-import doesn't silently start
// dropping a different row if upstream's palette values shift — see build plan §3.1.
const DROPPED_PRODUCT_TYPE = "Spatial Computing OS / App";

// Exact expected header row, in order. If upstream ever changes this, the import should fail
// loudly, not silently remap or drop a column.
const EXPECTED_HEADER = [
  "No", "Product Type", "Primary", "On Primary", "Secondary", "On Secondary", "Accent",
  "On Accent", "Background", "Foreground", "Card", "Card Foreground", "Muted",
  "Muted Foreground", "Border", "Destructive", "On Destructive", "Ring", "Notes",
];

type Palette = {
  id: number;
  productType: string;
  primary: string;
  onPrimary: string;
  secondary: string;
  onSecondary: string;
  accent: string;
  onAccent: string;
  background: string;
  foreground: string;
  card: string;
  cardForeground: string;
  muted: string;
  mutedForeground: string;
  border: string;
  destructive: string;
  onDestructive: string;
  ring: string;
  notes: string;
};

function parseArgs(argv: string[]): { source: string; sha: string } {
  const args = new Map<string, string>();
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith("--")) {
      args.set(argv[i].slice(2), argv[i + 1]);
      i++;
    }
  }
  const source = args.get("source");
  const sha = args.get("sha");
  if (!source || !sha) {
    throw new Error(
      "Usage: npx tsx lib/design/build/import-uupm.ts --source <path> --sha <upstream-commit-sha>"
    );
  }
  if (!/^[0-9a-f]{40}$/i.test(sha)) {
    throw new Error(`--sha must be a full 40-character commit SHA, got: ${sha}`);
  }
  return { source, sha };
}

function resolveCsvPath(source: string): string {
  const asFile = path.resolve(source);
  if (asFile.toLowerCase().endsWith(".csv")) return asFile;
  const insideClone = path.resolve(source, "src/ui-ux-pro-max/data/colors.csv");
  if (existsSync(insideClone)) return insideClone;
  throw new Error(`Could not find colors.csv at ${asFile} or ${insideClone}`);
}

// A small, direct RFC4180 field parser — not a general CSV library, since this script has
// exactly one file with a known, fixed shape to read (the 19 Border rows are the only quoted
// fields in the whole file, quoted because their rgba(...) values contain commas). Assumes
// LF-only input; call normalizeLineEndings first.
function parseCsv(content: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let inQuotes = false;
  let i = 0;
  while (i < content.length) {
    const char = content[i];
    if (inQuotes) {
      if (char === '"' && content[i + 1] === '"') {
        field += '"';
        i += 2;
        continue;
      }
      if (char === '"') {
        inQuotes = false;
        i++;
        continue;
      }
      field += char;
      i++;
      continue;
    }
    if (char === '"') {
      inQuotes = true;
      i++;
      continue;
    }
    if (char === ",") {
      row.push(field);
      field = "";
      i++;
      continue;
    }
    if (char === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
      i++;
      continue;
    }
    field += char;
    i++;
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

// Normalises CRLF (and any lone CR) to LF before anything else touches the content — parsing
// and the recorded content hash both run on this normalised string, so the digest recorded in
// PROVENANCE.md doesn't depend on which line-ending convention the checkout happened to use
// (the source repo's colors.csv is CRLF on disk as vendored; a Windows vs. Unix checkout of
// the SAME commit can still disagree on line endings depending on the cloning machine's git
// config, even though the committed blob is identical).
function normalizeLineEndings(content: string): string {
  return content.replace(/\r\n/g, "\n").replace(/\r/g, "\n");
}

// The only format inconsistency in colors.csv (per the uupm port audit, §2.2): 19 Border rows
// use rgba(255,255,255,0.08) instead of the hex6 every other row (including the other 173
// Border rows) uses. Normalised to 8-digit hex (#RRGGBBAA, CSS Color 4 order) so the whole
// Border column is uniformly hex — alpha is preserved, not discarded, since a deliberately
// subtle translucent border on a dark palette is a real design choice, not noise.
function normalizeBorder(value: string): string {
  const rgbaMatch = /^rgba\((\d+),(\d+),(\d+),([\d.]+)\)$/.exec(value.trim());
  if (!rgbaMatch) return value;
  const [, r, g, b, a] = rgbaMatch;
  const toHex2 = (n: number) => Math.round(n).toString(16).padStart(2, "0").toUpperCase();
  const alphaByte = Math.round(parseFloat(a) * 255);
  return `#${toHex2(Number(r))}${toHex2(Number(g))}${toHex2(Number(b))}${toHex2(alphaByte)}`;
}

function rowToPalette(header: string[], row: string[]): Palette {
  const get = (name: string): string => {
    const idx = header.indexOf(name);
    const value = row[idx];
    if (value === undefined) throw new Error(`Missing column "${name}" in row: ${row.join(",")}`);
    return value;
  };
  return {
    id: Number(get("No")),
    productType: get("Product Type"),
    primary: get("Primary"),
    onPrimary: get("On Primary"),
    secondary: get("Secondary"),
    onSecondary: get("On Secondary"),
    accent: get("Accent"),
    onAccent: get("On Accent"),
    background: get("Background"),
    foreground: get("Foreground"),
    card: get("Card"),
    cardForeground: get("Card Foreground"),
    muted: get("Muted"),
    mutedForeground: get("Muted Foreground"),
    border: normalizeBorder(get("Border")),
    destructive: get("Destructive"),
    onDestructive: get("On Destructive"),
    ring: get("Ring"),
    notes: get("Notes"),
  };
}

function main() {
  const { source, sha } = parseArgs(process.argv.slice(2));
  const csvPath = resolveCsvPath(source);

  const raw = readFileSync(csvPath, "utf8");
  const normalized = normalizeLineEndings(raw);
  const sourceSha256 = createHash("sha256").update(normalized, "utf8").digest("hex");

  const rows = parseCsv(normalized).filter((r) => r.length > 1 || r[0] !== "");
  const [header, ...dataRows] = rows;
  if (header.join(",") !== EXPECTED_HEADER.join(",")) {
    throw new Error(
      `colors.csv header changed since this script was written.\nExpected: ${EXPECTED_HEADER.join(",")}\nGot:      ${header.join(",")}`
    );
  }

  const totalRowCount = dataRows.length;
  const allPalettes = dataRows.map((row) => rowToPalette(header, row));
  const droppedRows = allPalettes.filter((p) => p.productType === DROPPED_PRODUCT_TYPE);
  if (droppedRows.length !== 1) {
    throw new Error(
      `Expected exactly 1 row with Product Type "${DROPPED_PRODUCT_TYPE}", found ${droppedRows.length}. Aborting rather than importing a row count the plan didn't anticipate.`
    );
  }
  const palettes = allPalettes.filter((p) => p.productType !== DROPPED_PRODUCT_TYPE);

  const rgbaBordersNormalized = dataRows.filter((row) =>
    /^rgba\(/.test(row[header.indexOf("Border")].trim())
  ).length;

  writeFileSync(
    path.join(OUT_DIR, "palettes.json"),
    JSON.stringify(palettes, null, 2) + "\n",
    "utf8"
  );

  const importDate = new Date().toISOString().slice(0, 10);

  const provenance = `# Provenance — lib/design/data/palettes.json

**GENERATED FILE. Do not hand-edit \`palettes.json\`.** It is fully overwritten every time
\`lib/design/build/import-uupm.ts\` runs — a hand edit survives only until the next re-import,
which silently discards it. Corrections belong in a sibling \`lib/design/data/overrides.json\`
(not created by this import — wire it in at the point something actually needs correcting),
merged at build time by whatever reads \`palettes.json\`. This is the same warning
\`import-uupm.ts\`'s own header comment carries — repeated here because JSON has no comment
syntax, so it can't live inside \`palettes.json\` itself without breaking \`jq 'length'\` on what
must stay a plain ${palettes.length}-element array.

## Source

- Repository: ${REPO_URL}
- Pinned commit SHA: \`${sha}\`
- Import date: ${importDate}
- File imported: \`src/ui-ux-pro-max/data/colors.csv\`
- Source file SHA-256 (after CRLF→LF normalisation — the committed blob is CRLF on disk, and
  hashing before normalising would make the digest depend on the checkout's line-ending
  behaviour, not just the content): \`${sourceSha256}\`
- License: MIT — see /THIRD_PARTY_NOTICES.md at the repo root.

## Row counts

| File | Upstream rows | Imported rows | Dropped |
|---|---:|---:|---|
| \`colors.csv\` | ${totalRowCount} | ${palettes.length} | 1 — \`${DROPPED_PRODUCT_TYPE}\` (No. ${droppedRows[0].id}), the single WCAG AA body-text failure the audit found (Background/Foreground contrast) |

## Normalisation applied

- ${rgbaBordersNormalized} \`Border\` values in \`rgba(r,g,b,a)\` form were converted to 8-digit hex
  (\`#RRGGBBAA\`) so the whole \`Border\` column is uniformly hex; alpha is preserved, not dropped.
  All other columns were already consistently \`#RRGGBBXX\`/\`#RRGGBB\` and untouched.
- Original upstream row numbers (the CSV's own \`No\` column) are preserved as each palette's
  \`id\` rather than renumbered 1..${palettes.length} — there is a gap at \`${droppedRows[0].id}\` where the
  dropped row was. This keeps every \`id\` traceable back to the exact upstream row it came from.

## Re-import

Re-import deliberately, quarterly at most — this is static reference data, not something with
security pressure to stay current (build plan §3.4). Before re-importing, gate on
\`validate-contrast.ts\`/\`validate-fonts.ts\` if/when those exist (not built by this import; see
Task 1.4's log entry in \`docs/kondo-v2-execution.md\` for why they're out of scope here).

    npx tsx lib/design/build/import-uupm.ts --source <path-to-clone-or-colors.csv> --sha <commit-sha>
`;

  writeFileSync(path.join(OUT_DIR, "PROVENANCE.md"), provenance, "utf8");

  console.log(`Imported ${palettes.length} palettes (dropped ${droppedRows.length}, from ${totalRowCount} upstream rows).`);
  console.log(`Normalised ${rgbaBordersNormalized} rgba() Border values to #RRGGBBAA hex.`);
  console.log(`Source SHA-256 (post-LF-normalisation): ${sourceSha256}`);
  console.log(`Wrote ${path.join(OUT_DIR, "palettes.json")}`);
  console.log(`Wrote ${path.join(OUT_DIR, "PROVENANCE.md")}`);
}

main();
